import type { CoreFood, DishTemplate, Nutrients, Portion } from "./types.ts";

/**
 * Núcleo curado: los alimentos que más aparecen en la alimentación de Juan
 * (desayuno colombiano, corrientazo, cenas, domicilios, fiestas).
 *
 * - `ref` apunta a la base unificada (TCAC 2015 o USDA FDC).
 * - Cuando la TCAC tiene valores dudosos (leguminosas, pasta y carnes "cocidas"
 *   con humedad de crudo) se usa la porción de intercambio de las GABA 2020 o el USDA.
 * - Gramos de porción: GABA/PAE cuando existen; si no, estimación documentada
 *   en docs/nutricion/research_notes (Tabla D) y marcada como ESTIMATE.
 */

type P = Omit<Portion, "label">;
const p = (unit: P["unit"], grams: number, basis: P["basis"] = "ESTIMATE"): P => ({ unit, grams, basis });

const n = (kcal: number, protein_g: number, fat_g: number, carb_g: number, fiber_g = 0, alcohol_g = 0, water_g = 0): Nutrients => ({
  kcal,
  protein_g,
  fat_g,
  carb_g,
  fiber_g,
  alcohol_g,
  water_g,
});

/** Bebida alcohólica destilada sin azúcar: kcal solo del etanol (densidad 0,789). */
const spirit = (abvPct: number): Nutrients => {
  const alcohol = Math.round(abvPct * 0.789 * 10) / 10;
  return n(Math.round(alcohol * 7), 0, 0, 0, 0, alcohol, 100 - alcohol);
};

